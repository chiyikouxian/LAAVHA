"""Install the reproducible mission source into scratch and build its target."""
import argparse,hashlib,json,subprocess
from pathlib import Path
from mission import ROOT,CONFIG


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--ns3-root',type=Path,default=Path('/home/suwen/ns-3.45'));args=ap.parse_args()
    nr=args.ns3_root/'contrib/nr'
    if not nr.exists():
        subprocess.run(['git','clone','--depth','1','--branch','v4.1','https://gitlab.com/cttc-lena/nr.git',str(nr)],check=True)
    version=subprocess.check_output(['git','rev-parse','HEAD'],cwd=nr,text=True).strip()
    if version!='5606a4e96b3a0bdbe7a5ecb9bbda10d69da3a7a8':raise ValueError('Expected the pinned 5G-LENA v4.1 commit')
    patch=ROOT/'ns3/nr-v4.1-disjoint-addresses.patch'
    applied=subprocess.run(['git','apply','--reverse','--check',str(patch)],cwd=nr,capture_output=True).returncode==0
    if not applied:subprocess.run(['git','apply','--check',str(patch)],cwd=nr,check=True);subprocess.run(['git','apply',str(patch)],cwd=nr,check=True)
    def array(values):return '{'+','.join(format(float(v),'.12g') for v in values)+'}'
    bounds=CONFIG['building_bounds_m']
    header='// Generated by build.py from config.json. Do not edit independently.\n#pragma once\n#include <array>\nnamespace mission_config {\n'
    header+='constexpr std::array<std::array<double,3>,3> sites{{'+','.join(array(v) for v in CONFIG['sites'])+'}};\n'
    for name,value in [('start',CONFIG['start']),('pathloss',CONFIG['pathloss_exponents']),('reference_loss',CONFIG['reference_loss_db']),('building_low',[b[0] for b in bounds]),('building_high',[b[1] for b in bounds])]:
        header+=f'constexpr std::array<double,3> {name}'+array(value)+';\n'
    for name,key in [('duration','duration_s'),('period','period_s'),('warmup','warmup_s'),('interruption','switch_interruption_s'),('preview_mbps','preview_mbps'),('imaging_mbps','imaging_mbps'),('obstruction_db','obstruction_loss_db')]:
        header+=f'constexpr double {name}={float(CONFIG[key]):.12g};\n'
    header+='}\n';(ROOT/'ns3/mission-config.h').write_text(header)
    src=ROOT/'ns3/laavha-mission.cc';link=args.ns3_root/'scratch/laavha-mission.cc'
    if link.exists() and link.resolve()!=src:raise ValueError(f'Refusing to replace unrelated source {link}')
    if not link.exists():link.symlink_to(src)
    hlink=args.ns3_root/'scratch/mission-config.h'
    if not hlink.exists():hlink.symlink_to(ROOT/'ns3/mission-config.h')
    subprocess.run([str(args.ns3_root/'ns3'),'configure','--enable-examples'],cwd=args.ns3_root,check=True)
    subprocess.run([str(args.ns3_root/'ns3'),'build','laavha-mission','-j','4'],cwd=args.ns3_root,check=True)
    (ROOT/'artifacts/platform.json').write_text(json.dumps({'ns3_version':(args.ns3_root/'VERSION').read_text().strip(),'nr_commit':version,'dependency_patch_sha256':hashlib.sha256(patch.read_bytes()).hexdigest(),'source_sha256':hashlib.sha256(src.read_bytes()).hexdigest()},indent=2)+'\n')


if __name__=='__main__':main()
